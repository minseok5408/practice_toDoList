export type TranslationKey = keyof typeof ko;
export type Translator = (
  key: TranslationKey,
  values?: Record<string, string | number>,
) => string;

export function resolveLanguage(
  language: AppLanguage,
  systemLanguages: readonly (string | null | undefined)[] = [],
): 'ko' | 'en' {
  if (language !== 'system') {
    return language;
  }

  for (const systemLanguage of systemLanguages) {
    const languageCode = systemLanguage?.toLowerCase().split(/[-_]/)[0];
    if (languageCode === 'ko' || languageCode === 'en') {
      return languageCode;
    }
  }

  return 'ko';
}

export function createTranslator(language: 'ko' | 'en'): Translator {
  const dictionary = language === 'ko' ? ko : en;

  return (key, values) => {
    let translated: string = dictionary[key];

    Object.entries(values ?? {}).forEach(([name, value]) => {
      translated = translated.replace(`{${name}}`, String(value));
    });

    return translated;
  };
}
